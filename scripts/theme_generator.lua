    end

    component("text_unselected", c.foreground, c.background)
    component("text_selected", c.foreground, c.selection)
    component("ribbon_unselected", c.comment, c.popupmenu)
    component("ribbon_selected", c.background, c.blue)
    component("table_title", c.blue, c.background)
