local function write(output, relative, content, files)
    local path = output .. "/" .. relative
    vim.fn.mkdir(vim.fs.dirname(path), "p")
    local normalized = content:gsub("\n+$", "")
    vim.fn.writefile(vim.split(normalized, "\n", { plain = true }), path)
    files[#files + 1] = relative
end

function M.generate(output)
    output = vim.fs.normalize(output)
    vim.fn.mkdir(output, "p")

    local themes = {}
    for _, variant in ipairs(variants) do
        for _, appearance in ipairs(appearances) do
            themes[#themes + 1] = derive(appearance, variant)
        end
    end

    local files = {}
    local windows_schemes = {}
    local palette_data = {}

    for _, theme in ipairs(themes) do
        windows_schemes[#windows_schemes + 1] = windows_terminal(theme)
        palette_data[#palette_data + 1] = palette_export(theme)

        write(output, "wezterm/" .. theme.slug .. ".toml", wezterm(theme), files)
        write(output, "alacritty/" .. theme.slug .. ".toml", alacritty(theme), files)
        write(output, "kitty/" .. theme.slug .. ".conf", kitty(theme), files)
        write(output, "ghostty/" .. theme.slug, ghostty(theme), files)
        write(output, "fzf/" .. theme.slug .. ".sh", fzf(theme), files)
        write(output, "helix/" .. theme.slug:gsub("-", "_") .. ".toml", helix(theme), files)
        write(output, "pi/" .. theme.slug .. ".json", pi_theme(theme), files)
        write(output, "eza/" .. theme.slug .. ".yml", eza(theme), files)
        write(output, "bat/" .. theme.slug .. ".tmTheme", bat(theme), files)
        write(output, "delta/" .. theme.slug .. ".gitconfig", delta(theme), files)
        write(output, "starship/" .. theme.slug .. ".toml", starship(theme), files)
        write(output, "zellij/" .. theme.slug .. ".kdl", zellij(theme), files)
        write(output, "lazygit/" .. theme.slug .. ".yml", lazygit(theme), files)
    end

    write(output, "windows-terminal/nova.json", json_encode({ schemes = windows_schemes }) .. "\n", files)
    write(output, "palettes/nova.json", json_encode({ palettes = palette_data }) .. "\n", files)
    table.sort(files)
    return files
end

return M
