    component("frame_highlight", c.current_match, c.background)
    component("exit_code_success", c.green, c.background)
    component("exit_code_error", c.red, c.background)

    vim.list_extend(lines, {
        "    multiplayer_user_colors {",
        string.format('      player_1 "%s"', c.red),
        string.format('      player_2 "%s"', c.orange),
        string.format('      player_3 "%s"', c.yellow),
        string.format('      player_4 "%s"', c.green),
        string.format('      player_5 "%s"', c.teal),
        string.format('      player_6 "%s"', c.blue),
        string.format('      player_7 "%s"', c.violet),
        string.format('      player_8 "%s"', c.purple),
        string.format('      player_9 "%s"', c.comment),
        string.format('      player_10 "%s"', c.foreground),
        "    }",
        "  }",
        "}",
    })
    return join(lines)
end

