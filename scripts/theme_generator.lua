        { "Escape and special", "constant.character.escape, string.regexp", c.orange },
        { "Keyword", "keyword, storage.modifier", c.purple },
        { "Type", "storage.type, entity.name.type, entity.name.class, support.type", c.red },
        { "Function", "entity.name.function, support.function, meta.function-call", c.blue },
        { "Property", "variable.other.member, support.variable.property", c.violet },
        { "Tag", "entity.name.tag", c.orange },
        { "Markup heading", "markup.heading", c.blue, "bold" },
        { "Markup link", "markup.underline.link", c.teal, "underline" },
        { "Markup inserted", "markup.inserted", c.green },
        { "Markup deleted", "markup.deleted", c.red },
        { "Invalid", "invalid, invalid.illegal", c.red, "bold" },
    }
    local lines = {
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
        '<plist version="1.0">',
        "<dict>",
        "  <key>name</key>",
        "  <string>" .. theme.slug .. "</string>",
        "  <key>author</key>",
        "  <string>Nova theme generator</string>",
        "  <key>settings</key>",
        "  <array>",
        "    <dict>",
        "      <key>settings</key>",
        "      <dict>",
        "        <key>background</key><string>" .. c.background .. "</string>",
        "        <key>foreground</key><string>" .. c.foreground .. "</string>",
        "        <key>caret</key><string>" .. c.red .. "</string>",
        "        <key>selection</key><string>" .. c.selection .. "</string>",
        "        <key>lineHighlight</key><string>" .. c.stripline .. "</string>",
        "        <key>invisibles</key><string>" .. c.inconspicuous .. "</string>",
        "      </dict>",
        "    </dict>",
    }
    for _, entry in ipairs(entries) do
        vim.list_extend(lines, {
            "    <dict>",
            "      <key>name</key><string>" .. entry[1] .. "</string>",
            "      <key>scope</key><string>" .. entry[2] .. "</string>",
            "      <key>settings</key>",
            "      <dict>",
            "        <key>foreground</key><string>" .. entry[3] .. "</string>",
        })
        if entry[4] then
            lines[#lines + 1] = "        <key>fontStyle</key><string>" .. entry[4] .. "</string>"
        end
        vim.list_extend(lines, { "      </dict>", "    </dict>" })
    end
    vim.list_extend(lines, { "  </array>", "</dict>", "</plist>" })
    return join(lines)
end

local function delta(theme)
    local c = theme.colors
    local blend = require("nova.utils").blend
    local plus_emph = blend(c.green, c.background, theme.appearance == "light" and 0.16 or 0.35)
    local minus_emph = blend(c.red, c.background, theme.appearance == "light" and 0.16 or 0.35)
    return header("#") .. join({
        string.format('[delta "%s"]', theme.slug),
        "    dark = " .. tostring(theme.appearance == "dark"),
        "    syntax-theme = " .. theme.slug,
        string.format('    minus-style = syntax "%s"', c.diff_delete_bg),
        string.format('    minus-emph-style = syntax "%s"', minus_emph),
        string.format('    plus-style = syntax "%s"', c.diff_add_bg),
        string.format('    plus-emph-style = syntax "%s"', plus_emph),
        "    zero-style = syntax",
        string.format('    commit-style = bold "%s"', c.violet),
        string.format('    file-style = bold "%s"', c.blue),
        string.format('    file-decoration-style = "%s"', c.splitline),
        string.format('    hunk-header-style = syntax "%s"', c.popupmenu),
        string.format('    hunk-header-decoration-style = "%s" box', c.splitline),
        string.format('    line-numbers-minus-style = "%s"', c.red),
        string.format('    line-numbers-zero-style = "%s"', c.inconspicuous),
        string.format('    line-numbers-plus-style = "%s"', c.green),
    })
end

local function starship(theme)
    local c = theme.colors
    local palette_name = theme.slug:gsub("-", "_")
    local values = {
        black = theme.ansi[1],
        red = c.red,
        green = c.green,
        yellow = c.yellow,
        blue = c.blue,
        purple = c.purple,
        cyan = c.teal,
        white = theme.ansi[8],
        orange = c.orange,
        violet = c.violet,
        foreground = c.foreground,
        comment = c.comment,
        muted = c.inconspicuous,
        background = c.background,
        surface = c.stripline,
        selection = c.selection,
        accent = c.target,
    }
    local lines = {
        header("#"):gsub("\n$", ""),
        string.format("palette = %q", palette_name),
        "",
        string.format("[palettes.%s]", palette_name),
    }
    local keys = vim.tbl_keys(values)
    table.sort(keys)
    for _, key in ipairs(keys) do
        lines[#lines + 1] = string.format("%s = %q", key, values[key])
    end
    return join(lines)
end

local function zellij(theme)
    local c = theme.colors
    local lines = {
        header("//"):gsub("\n$", ""),
        "themes {",
        "  " .. theme.slug .. " {",
        string.format('    fg "%s"', c.foreground),
        string.format('    bg "%s"', c.background),
        string.format('    black "%s"', theme.ansi[1]),
        string.format('    red "%s"', theme.ansi[2]),
        string.format('    green "%s"', theme.ansi[3]),
        string.format('    yellow "%s"', theme.ansi[4]),
        string.format('    blue "%s"', theme.ansi[5]),
        string.format('    magenta "%s"', theme.ansi[6]),
        string.format('    cyan "%s"', theme.ansi[7]),
        string.format('    white "%s"', theme.ansi[8]),
        string.format('    orange "%s"', c.orange),
    }

    local function component(name, base, background)
