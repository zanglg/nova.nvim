local function join(lines)
    return table.concat(lines, "\n") .. "\n"
end

local function header(prefix)
    return string.format("%s Generated by scripts/generate_themes.lua; do not edit.\n", prefix)
end

local function slug(appearance, variant)
    return "nova-" .. appearance .. (variant == "default" and "" or "-" .. variant)
end

local function display_name(appearance, variant)
    local words = { "Nova", appearance:sub(1, 1):upper() .. appearance:sub(2) }
    if variant ~= "default" then
        words[#words + 1] = variant:sub(1, 1):upper() .. variant:sub(2)
    end
    return table.concat(words, " ")
end

local function json_encode(value, level)
    level = level or 0
    local indent = string.rep("  ", level)
    local child_indent = string.rep("  ", level + 1)

    if type(value) ~= "table" then
        return vim.json.encode(value)
    end

    if vim.islist(value) then
        if #value == 0 then
            return "[]"
        end
        local encoded = {}
        for _, item in ipairs(value) do
            encoded[#encoded + 1] = child_indent .. json_encode(item, level + 1)
        end
        return "[\n" .. table.concat(encoded, ",\n") .. "\n" .. indent .. "]"
    end

    local keys = vim.tbl_keys(value)
    table.sort(keys)
    if #keys == 0 then
        return "{}"
    end

    local encoded = {}
    for _, key in ipairs(keys) do
        encoded[#encoded + 1] = string.format(
            "%s%s: %s",
            child_indent,
            vim.json.encode(key),
            json_encode(value[key], level + 1)
        )
    end
    return "{\n" .. table.concat(encoded, ",\n") .. "\n" .. indent .. "}"
end

local function derive(appearance, variant)
    local colors = require("nova.colors").setup({ colors = {}, variant = variant }, appearance)
    local blend = require("nova.utils").blend
    local anchor = appearance == "dark" and "#ffffff" or "#000000"
    local function intense(color)
        return blend(color, anchor, 0.88)
    end

    return {
        appearance = appearance,
        variant = variant,
        slug = slug(appearance, variant),
        name = display_name(appearance, variant),
        colors = colors,
        ansi = {
            colors.background,
            colors.red,
            colors.green,
            colors.yellow,
            colors.blue,
            colors.purple,
            colors.teal,
            colors.foreground,
        },
        brights = {
            colors.comment,
            intense(colors.red),
            intense(colors.green),
            intense(colors.yellow),
            intense(colors.blue),
            intense(colors.purple),
            intense(colors.teal),
            intense(colors.foreground),
        },
    }
end

